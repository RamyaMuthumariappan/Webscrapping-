import re

# 1. Find all the "containers" that hold book information
books = web_page.find_all('article', class_='product_pod')

# 2. Create an empty list to store our data
books_list = []

for book in books:
    # Get the Title
    title = book.h3.a['title']

    # --- FIXED PRICE SECTION ---
    # Get the Price text (e.g., 'Â£51.77')
    price_text = book.find('p', class_='price_color').text

    # Use Regex to extract only the number (digits and decimal)
    # This ignores '£', 'Â', or any other encoding noise
    price_cleaned = re.findall(r"[-+]?\d*\.\d+|\d+", price_text)[0]
    price = float(price_cleaned)
    # ---------------------------

    # Get the Star Rating
    rating_classes = book.find('p', class_='star-rating')['class']
    rating = rating_classes[1]

    # Get Availability
    stock = book.find('p', class_='instock availability').text.strip()

    # Append as a dictionary to our list
    books_list.append({
        "Title": title,
        "Price": price,
        "Rating": rating,
        "Stock": stock
    })

print(f"Successfully extracted {len(books_list)} books!")

# Create the DataFrame
df = pd.DataFrame(books_list)

# Map the string ratings to numbers for better analysis

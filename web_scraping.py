import requests
import bs4
import re

books = web_page.find_all('article', class_='product_pod')
detailed_books = []

for book in books:
    # 1. Get the 'href' attribute (NOT 'url')
    relative_url = book.h3.a['href']

    # 2. Fix the URL path
    # On this site, relative links often look like 'catalogue/book_name'
    # or '../../../book_name'. We ensure it creates a valid link.
    clean_url = relative_url.replace('../../../', '')
    if "catalogue/" in clean_url:
        full_url = "https://books.toscrape.com/" + clean_url
    else:
        full_url = "https://books.toscrape.com/catalogue/" + clean_url

    # 3. Visit the individual page
    detail_page_res = requests.get(full_url)
    detail_soup = bs4.BeautifulSoup(detail_page_res.text, "lxml")

    # 4. Extract the Product Information Table
    # Analysts love this because it's structured data
    table = detail_soup.find('table', class_='table-striped')

    if table:
        rows = table.find_all('tr')
        info_dict = {}
        for row in rows:
            header = row.th.text.strip()
            value = row.td.text.strip()
            info_dict[header] = value

        # 5. Build our data entry
        detailed_books.append({
            "Title": book.h3.a['title'],
            "UPC": info_dict.get("UPC"),
            "Price_Excl_Tax": info_dict.get("Price (excl. tax)"),
            "Tax": info_dict.get("Tax"),
            "Availability": info_dict.get("Availability")
        })

print(f"Successfully scraped details for {len(detailed_books)} books!")

